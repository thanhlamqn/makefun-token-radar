// Token Radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// every rankable pre-token protocol below the watchlist floor: the early rows the radar exists to
// find. A protocol is pre-token when its index entry records no token (no market cap, no CoinGecko
// id, no symbol); the snapshot's live-token protocols are kept apart and shown as the market's own
// values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, and its base multiple is calibrated
// from the snapshot itself: for each category, the median market-cap-to-TVL ratio of the launched
// protocols in that category (three or more of them), falling back to the global median where a
// category has too few launched names. No protocol name is ever special-cased: the same function
// scores every row, and the calibration table is printed in the dashboard's Method view.
//
//   base         = tvl_usd x category_multiple
//   growth       = clamp(change_7d, -60, 150) per cent
//   growthMult   = 1 + (growth / 100) x (growth >= 0 ? 0.5 : 0.75)
//   maturity     = 0.6 + min(age_days, 1460) / 1460 x 0.4, x 0.85 when age_days < 90
//   implied      = max(1, round(base x growthMult x maturity))
//
// A decline hurts more than a rise helps (a falling TVL is a protocol losing its users), a
// protocol younger than 90 days is discounted (too young to judge), and age stops mattering after
// four years: a protocol that has run that long with no token is already fully mature.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

